/// The Armor Rating of template `uuid` at `tempering_level` (1..=10; higher
/// levels clamp to 10), or `None` for level 0 or a template with no temper table.
pub fn tempered_armor_value(uuid: &str, tempering_level: u64) -> Option<f32> {
    if tempering_level == 0 {
        return None;
    }
    let i = ARMOR_TEMPER
        .binary_search_by(|(u, _)| (*u).cmp(uuid))
        .ok()?;
    let row = (tempering_level.min(10) - 1) as usize;
    Some(ARMOR_TEMPER[i].1[row])
}
